-- ── Page content blocks (bilingual, admin-editable) ─────────────────────
create table if not exists public.page_content (
  id bigint generated by default as identity primary key,
  page text not null,
  section_key text not null,
  content_ar text,
  content_en text,
  updated_at timestamptz not null default now(),
  unique (page, section_key)
);

alter table public.page_content enable row level security;

create policy "Public read page content" on public.page_content
  for select using (true);
create policy "Authenticated insert page content" on public.page_content
  for insert to authenticated with check (true);
create policy "Authenticated update page content" on public.page_content
  for update to authenticated using (true) with check (true);
create policy "Authenticated delete page content" on public.page_content
  for delete to authenticated using (true);

