-- ── Articles table ───────────────────────────────────────────────────────
create table if not exists public.articles (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null,
  excerpt text not null,
  body text not null,
  date text not null,
  featured boolean not null default false,
  bg text not null default 'linear-gradient(135deg, #04334c 0%, #0a6b6b 100%)',
  img text,
  created_at timestamptz not null default now()
);

alter table public.articles enable row level security;

-- Anyone (including anonymous site visitors) can read articles.
create policy "Public read access" on public.articles
  for select using (true);

-- Only logged-in users (i.e. you, via the admin page) can write.
create policy "Authenticated insert" on public.articles
  for insert to authenticated with check (true);
create policy "Authenticated update" on public.articles
  for update to authenticated using (true) with check (true);
create policy "Authenticated delete" on public.articles
  for delete to authenticated using (true);

